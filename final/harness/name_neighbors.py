#!/usr/bin/env python3
"""L1 name neighbours (2026-10-22; docs/distill_to_tools.md, docs/tools_build_plan.md): when Lean reports `unknown identifier X` or
`unknown constant X` in a lean_check / lean_run result, list up to MAX_LINES real constants near X from the row's own Lean environment,
each with its one-line signature, so the model replaces a guessed name with one that exists instead of guessing again.

How it works
  1. unknown_names() reads X from Lean's own error text (both message styles: "Unknown identifier `X`" from v4.2x on and the older
     "unknown identifier 'X'"; same for constants). Names that are clearly local hypotheses or variables (`h`, `h1`, `hx`, `ih`, `this`, a
     single letter, anything with `✝`) are skipped: they are scoping slips, not library guesses.
  2. plan(): which namespaces to list. A qualified X = `A.B.stem` lists `A.B` (and its parent `A` when it has two or more components); an
     unqualified X lists the root namespace plus the row's context namespaces (the namespace open at the end of the file prefix and its
     ancestors, then the `open` commands of the header / prefix). Every X also asks for the constants whose LAST component equals its stem
     in any namespace (exact stem hits: `stem` written under the wrong namespace or without one).
  3. One Lean query in the row's environment (the same environment directory, toolchain, header / file prefix and lakefile options the
     check used; lake_runner, admitted by scorer.memgate like every compile) lists the constants of those namespaces (direct children,
     internal details dropped, the file's own private names under their user names) and the stem hits. The listing is cached on disk
     under the work root per (environment, toolchain, header hash, namespace), so a session pays for a namespace once and later sessions
     of the line pay nothing.
  4. rank() (pure Python): candidates whose stem is similar to X's stem (edit distance on characters, or twice the edit distance on
     `_`/camel-case word tokens, within max(2, len/3)); ranked by stem distance plus a namespace penalty (0 for X's own namespace or, for
     an unqualified X, a context namespace; 1 for the parent namespace / any other namespace of an unqualified X; else the namespace edit
     distance, at most 3), then by length and name.
  5. A second query prints the signatures of the chosen names (Lean's PrettyPrinter.ppSignature, collapsed to one line, cut at
     SIG_CHARS), cached per name in the same cache directory.
  Bounds: at most MAX_NAMES unknown names per result, MAX_LINES lines per result (shared round-robin between names), MAX_QUERIES Lean
  processes and SESSION_SECONDS of Lean wall time per Session (one Session per agent session), QUERY_TIMEOUT per process; a failed or
  timed-out query is not retried for the same namespaces in that session. Every failure path returns {} (the caller appends nothing).

Memory across sessions: record_missing() keeps <workspace>/missing_names.json, the names Lean reported unknown AND that the listing
confirmed are not constants of the environment as written, with their three nearest neighbours; missing_block() renders it for the next
session's opening message (the agent.py hook behind --name-neighbors).

Provenance rule (docs/distill_to_tools.md, "every Lean token a tool inserts comes from the proof being edited, from Lean at run time, or
from a table generated by a stated rule"): this tool inserts nothing into a proof. The names it shows come from the row's Lean environment
at run time (Lean lists them), triggered by a name the model itself wrote and Lean rejected; the signatures are printed by Lean; the
ranking is a fixed string-distance rule. This module names no library declaration (its only Lean code is the query's meta-programming);
its tests use a synthetic fixture environment.

    python3 harness/name_neighbors.py --problem <row> --errors "<Lean error text>" [--work-root harness/work_x] [--version v4.27.0]
"""
