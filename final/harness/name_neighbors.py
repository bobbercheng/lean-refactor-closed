MAX_LINES = 8            # neighbour lines appended to one tool result (all unknown names together)
MAX_NAMES = 3            # unknown names looked up per tool result
MAX_QUERIES = 10         # Lean processes per Session (a cold lookup takes 2: the listing, then the signatures)
SESSION_SECONDS = 300.0  # Lean wall time per Session (memgate admission included; a heavy file prefix costs ~10 s per query)
QUERY_TIMEOUT = 150.0    # seconds per Lean process
MAX_NAMESPACES = 8       # namespaces listed for one unqualified name (root included)
HIT_CAP = 400            # exact-stem hits kept per stem by the Lean query
SIG_CHARS = 160          # one-line signature cut
MISSING_FILE = "missing_names.json"
MISSING_SHOW = 12
CACHE_DIR = ".name_neighbors"
QUERY_CMD = "lra_name_neighbors_query"

NOTE = ("name_neighbors: real constants of this environment near each unknown name, listed by Lean at run time, closest spelling "
        "first, each with its signature. Use one of them (check its arguments) instead of guessing the unknown name again.")

_UNKNOWN = re.compile(r"[Uu]nknown (?:identifier|constant) (?:`([^`\n]+)`|'(\S+?)'(?=[\s.,:;)]|$))")
_LOCAL = re.compile(r"(?:h|ih|hh)\d*'*|h[a-z]{1,3}\d*'*|[A-Za-z]\d*'*|this|x✝.*")
# 2026-10-25 (b63 launch set item 5, docs/adaptive_plan_93.md §4.1 / bottlenecks §4 item 5): `inst*` names are no longer noise. A named
# instance is what a `letI : C := NS.instFoo` pin needs (heartbeat cost: an interleaved-type row 1579 -> 1297 hb), and the model could not
# reach instance names through any tool while they were filtered here. Syntax-node / parser / delaborator stems stay noise.
_NOISE = re.compile(r"«|(?:command|term|tactic|unexpand|delab)[A-Z«_]|_")   # syntax-node / internal stems (start only)
_COMP = re.compile(r"«[^»]*»|[^.«»]+")


# ---- names ---------------------------------------------------------------------------------------------------------------------------
def split_name(n: str) -> list[str]:
    """Components of a dotted Lean name; «…» components keep their dots."""
    return _COMP.findall(n)


def ns_stem(n: str) -> tuple[str, str]:
    p = split_name(n)
    return ".".join(p[:-1]), (p[-1] if p else "")


def unknown_names(errors) -> list[str]:
    """Names Lean reported as unknown identifiers / constants, in order of first appearance (a str or a list of error strings)."""
    text = errors if isinstance(errors, str) else "\n".join(str(e) for e in errors or [])
    out: list[str] = []
    for m in _UNKNOWN.finditer(text):
        n = (m.group(1) or m.group(2) or "").strip()
        if n and n not in out:
            out.append(n)
    return out


def skip_name(n: str) -> bool:
    """A local hypothesis / variable slip (`h`, `hx`, `h1'`, `ih`, `this`, a single letter, `x✝`), a `hx.foo` field use of one, or junk."""
    if not n or "✝" in n or n.startswith(("_", ".")):
        return True
    first = split_name(n)[0] if split_name(n) else n
    return bool(_LOCAL.fullmatch(first))


def noise(full: str) -> bool:
    """Instances, syntax-node and parser constants, the query's own command: never what a proof names."""
    stem = ns_stem(full)[1]
    return bool(_NOISE.match(stem)) or QUERY_CMD in full.lower()


# ---- distances -----------------------------------------------------------------------------------------------------------------------
def stem_tokens(s: str) -> list[str]:
    return [t for t in re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", s).lower().split("_") if t]


def lev(a, b, cap: int) -> int:
    """Levenshtein distance of two sequences, or cap + 1 when it exceeds cap (banded early exit)."""
    if a == b:
        return 0
    la, lb = len(a), len(b)
    if abs(la - lb) > cap:
        return cap + 1
    prev = list(range(lb + 1))
    for i in range(1, la + 1):
        cur = [i] + [0] * lb; ai = a[i - 1]; lo = i
        for j in range(1, lb + 1):
            v = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ai != b[j - 1]))
            cur[j] = v
            if v < lo:
                lo = v
        if lo > cap:
            return cap + 1
        prev = cur
    return min(prev[lb], cap + 1)


def lcs(a: list, b: list) -> int:
    """Length of the longest common subsequence."""
    prev = [0] * (len(b) + 1)
    for x in a:
        cur = [0]
        for j, y in enumerate(b):
            cur.append(prev[j] + 1 if x == y else max(prev[j + 1], cur[j]))
        prev = cur
    return prev[-1]


def indel(a: list, b: list) -> int:
    """Insertions + deletions turning a into b (no substitution)."""
    return len(a) + len(b) - 2 * lcs(a, b)


def threshold(want_stem: str) -> int:
    return max(2, len(want_stem) // 3)


def stem_distance(cand: str, want: str, cap: int | None = None) -> int:
    """min(character edit distance, 2 x word-token insert/delete distance), capped at cap + 1. Word tokens split at `_` and camel-case
    humps; the token distance counts only when the two stems share all words but at most one on each side (one word added, dropped,
    replaced or moved: `foo_le_bar` / `foo_le_bar_left`), and a token is never substituted, so a replaced word costs 2 x 2 and two
    different one-word stems are 2 x 2 apart, not 2."""
    cap = threshold(want) if cap is None else cap
    d1 = lev(cand, want, cap)
    if d1 == 0:
        return 0
    tc, tw = stem_tokens(cand), stem_tokens(want); common = lcs(tc, tw)
    d2 = 2 * (len(tc) + len(tw) - 2 * common) if max(len(tc), len(tw)) - common <= 1 else cap + 1
    return min(d1, d2, cap + 1)


@dataclass
class Plan:
    want: str
    ns: str
    stem: str
    qualified: bool
    parent: str | None
    namespaces: list[str]
    context: tuple = ()


def plan(want: str, context: tuple | list = ()) -> Plan:
    ns, stem = ns_stem(want)
    if ns:
        parent = ns_stem(ns)[0] if len(split_name(ns)) >= 2 else None
        return Plan(want, ns, stem, True, parent, [ns] + ([parent] if parent else []), tuple(context))
    nss = [""] + [c for c in dict.fromkeys(context) if c][:MAX_NAMESPACES - 1]
    return Plan(want, "", stem, False, None, nss, tuple(context))


def ns_penalty(p: Plan, ns_c: str) -> int:
    if p.qualified:
        if ns_c == p.ns:
            return 0
        if p.parent is not None and ns_c == p.parent:
            return 1
        return min(3, lev(ns_c, p.ns, 3))
    return 0 if (ns_c == "" or ns_c in p.context) else 1


def rank(p: Plan, listings: dict, hits: list[str], limit: int = MAX_LINES) -> list[str]:
    """Up to `limit` full names near p.want: similar stems in the listed namespaces, plus exact stem hits elsewhere (when X's own
    namespace has no constants at all, only hits whose namespace is itself a near spelling of X's namespace)."""
    thr = threshold(p.stem); want_toks = set(stem_tokens(p.stem)); best: dict[str, tuple] = {}
    for ns in p.namespaces:
        for full in listings.get(ns) or ():
            if full == p.want or noise(full):
                continue
            ns_c, st = ns_stem(full)
            if abs(len(st) - len(p.stem)) > thr and not (want_toks & set(stem_tokens(st))):
                continue
            d = stem_distance(st, p.stem, thr)
            if d > thr:
                continue
            k = (d + ns_penalty(p, ns_c), d, len(full), full)
            if full not in best or k < best[full]:
                best[full] = k
    own_empty = p.qualified and not (listings.get(p.ns) or [])
    ns_thr = max(1, len(p.ns) // 3)
    for full in hits or ():
        if full == p.want or noise(full):
            continue
        ns_c = ns_stem(full)[0]
        if own_empty and lev(ns_c, p.ns, ns_thr) > ns_thr:
            continue
        k = (ns_penalty(p, ns_c), 0, len(full), full)
        if full not in best or k < best[full]:
            best[full] = k
    return [k[3] for k in sorted(best.values())][:limit]


def confirmed_missing(p: Plan, listings: dict) -> bool:
    """Lean listed every namespace X could be in (as written) and X is in none of them."""
    if any(ns not in listings for ns in (p.namespaces if not p.qualified else [p.ns])):
        return False
    if p.qualified:
        return p.want not in set(listings[p.ns])
    return all((f"{ns}.{p.stem}" if ns else p.stem) not in set(listings[ns]) for ns in p.namespaces)


def share_lines(per_name: dict[str, list[str]], total: int = MAX_LINES) -> dict[str, list[str]]:
    """Round-robin over the names (in order) until `total` lines are taken; names left with nothing are dropped."""
    out = {n: [] for n in per_name}; left = total; i = 0
    while left > 0:
        took = False
        for n, lst in per_name.items():
            if left > 0 and i < len(lst):
                out[n].append(lst[i]); left -= 1; took = True
        if not took:
            break
        i += 1
    return {n: v for n, v in out.items() if v}


def one_line(sig: str, limit: int = SIG_CHARS) -> str:
    s = re.sub(r"\s+", " ", sig).strip()
    return s if len(s) <= limit else s[:limit - 1].rstrip() + "…"


def render(nb: dict[str, list[str]]) -> str:
    """Text block for a lean_run result."""
    if not nb:
        return ""
    lines = ["NAME NEIGHBORS (" + NOTE.split(": ", 1)[1].rstrip(".") + "):"]
    for n, lst in nb.items():
        lines.append(f"  unknown `{n}`:")
        lines += [f"    {s}" for s in lst]
    return "\n".join(lines)


# ---- environment ---------------------------------------------------------------------------------------------------------------------
@dataclass
class EnvSpec:
    wd: Path                 # directory Lean runs in (lake env / plain lean)
    head: str                # header or file prefix (core, without the declaration's own modifiers); the query goes after it
    toolchain: str           # the environment's lean-toolchain
    lean_args: tuple = ()    # extra lean flags (the pin's lakefile options)
    context: tuple = ()      # namespaces an unqualified name may resolve in (current namespace chain, then `open`s)
    module: bool = False     # a `module` file (the query's elab needs a meta import there; retried with it)

    @property
    def key(self) -> str:
        h = hashlib.sha256(self.head.encode()).hexdigest()[:16]
        return re.sub(r"[^A-Za-z0-9_.-]", "_", f"{self.wd.name}__{self.toolchain}__{h}")


def context_namespaces(head: str, attached: str = "") -> tuple:
    """The namespace open at the end of `head` and its ancestors (innermost first), then the namespaces of its `open` commands (an
    `open … in` there scopes only the next command and is skipped), then those of the `open … in` lines in `attached` (the
    declaration's own modifiers: they open the namespace for the proof)."""
    from scorer.forbidden import strip_lean_comments
    from scorer.compile import current_namespace
    text = strip_lean_comments(head); out: list[str] = []
    parts = split_name(current_namespace(text) or "")
    for i in range(len(parts), 0, -1):
        out.append(".".join(parts[:i]))
    opens = [(m.group(1), False) for m in re.finditer(r"^[ \t]*open[ \t]+([^\n]*)$", text, re.M)]
    opens += [(m.group(1), True) for m in re.finditer(r"(?:^|\s)open[ \t]+([^\n]*?)[ \t]+in\b", strip_lean_comments(attached), re.M)]
    for line, own in opens:
        if not own and re.search(r"\bin[ \t]*$", line):
            continue
        for tok in re.split(r"\b(?:hiding|renaming)\b|\(", line)[0].split():
            if tok != "scoped" and re.fullmatch(r"[^\s()\[\]{}]+", tok) and tok not in out:
                out.append(tok)
    return tuple(out[:MAX_NAMESPACES - 1])


def env_spec(row: dict, version: str) -> EnvSpec:
    """The environment a lean_check of `row` on `version` compiles in (scorer.compile.compile_putnam / compile_project)."""
    from scorer.compile import env_dir, project_env_dir, file_prefix, split_modifiers, lakefile_options, _MODULE_LINE
    if row["source"] == "putnambench":
        wd = env_dir(version); head = row["header"].rstrip() + "\n"; args: tuple = ()
    else:
        from scorer import compile as _c
        wd = project_env_dir(row["source"], version)
        core, mods = split_modifiers(file_prefix(row, version))
        m = getattr(_c, "_ATTACHED_IN").search(core)   # an `omit … in` / `set_option … in` that belongs to the declaration
        head = (core[:m.start()] if m else core).rstrip("\n") + "\n"
        attached = (core[m.start():] if m else "") + mods
        args = tuple(lakefile_options(row["source"], version))
    tc = wd / "lean-toolchain"
    toolchain = tc.read_text().strip().split(":")[-1] if tc.exists() else version
    ctx = context_namespaces(head, attached if row["source"] != "putnambench" else "")
    return EnvSpec(wd, head, toolchain, args, ctx, bool(_MODULE_LINE.match(head)))


# ---- the Lean query ------------------------------------------------------------------------------------------------------------------
def _lean_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def lean_name(n: str) -> str:
    e = "Name.anonymous"
    for c in split_name(n):
        c = c[1:-1] if c.startswith("«") and c.endswith("»") else c
        e = f"(Name.mkStr {e} {_lean_str(c)})"
    return e


QUERY = """open Lean Elab Command in
elab "{cmd}" : command => do
  let env ← getEnv
  let nss : Array Name := #[{nss}]
  let stems : Array String := #[{stems}]
  let sigs : Array Name := #[{sigs}]
  let mut lists := Array.replicate nss.size (#[] : Array Name)
  let mut hits := Array.replicate stems.size (#[] : Array Name)
  if nss.size + stems.size > 0 then
    for (n0, _) in env.constants.toList do
      let n := if isPrivateName n0 && (env.getModuleIdxFor? n0).isNone then privateToUserName n0 else n0
      unless n.isInternalDetail do
        let p := n.getPrefix
        for i in [0:nss.size] do
          if nss[i]! == p then
            lists := lists.modify i (·.push n)
        if let .str _ s := n then
          for i in [0:stems.size] do
            if stems[i]! == s && hits[i]!.size < {cap} then
              hits := hits.modify i (·.push n)
  for i in [0:nss.size] do
    logInfo m!"LRA_NN_NS {{i}}\\n{{"\\n".intercalate (lists[i]!.toList.map toString)}}"
  for i in [0:stems.size] do
    logInfo m!"LRA_NN_HIT {{i}}\\n{{"\\n".intercalate (hits[i]!.toList.map toString)}}"
  for nm in sigs do
    let s ← try
        let f ← liftTermElabM (PrettyPrinter.ppSignature nm)
        pure (toString f.fmt)
      catch _ => pure "?"
    logInfo m!"LRA_NN_SIG {{toString nm}}\\n{{s}}"

set_option maxHeartbeats 0 in
{cmd}
"""


def query_text(spec: EnvSpec, nss: list[str], stems: list[str], sigs: list[str], meta_import: bool = False) -> tuple[str, int]:
    """(file text, first line of the query) for one Lean run after the environment's head."""
    head = spec.head
    if meta_import:
        from scorer.compile import _with_measure_import
        head = _with_measure_import(head) or head
    text = head.rstrip("\n") + "\n\n"
    first = text.count("\n") + 1
    text += QUERY.format(cmd=QUERY_CMD, nss=", ".join(lean_name(n) for n in nss), stems=", ".join(_lean_str(s) for s in stems),
                         sigs=", ".join(lean_name(n) for n in sigs), cap=HIT_CAP)
    return text, first


def parse_messages(stdout: str) -> list[dict]:
    out = []
    for line in (stdout or "").splitlines():
        line = line.strip()
        if line.startswith("{"):
            try:
                out.append(json.loads(line))
            except ValueError:
                pass
    return out


def parse_query(msgs: list[dict], first: int, nss: list[str], stems: list[str], sigs: list[str]) -> dict | None:
    """{"ns": {ns: [names]}, "hits": {stem: [names]}, "sigs": {name: sig}}, or None when the query did not run (an error at its lines,
    or a missing answer)."""
    out = {"ns": {}, "hits": {}, "sigs": {}}
    for m in msgs:
        line = (m.get("pos") or {}).get("line") or 0
        if m.get("severity") == "error" and line >= first:
            return None
        if m.get("severity") != "information" or line < first:
            continue
        d = str(m.get("data", "")); head, _, rest = d.partition("\n")
        names = [x.strip() for x in rest.split("\n") if x.strip()]
        try:
            if head.startswith("LRA_NN_NS "):
                out["ns"][nss[int(head.split()[1])]] = names
            elif head.startswith("LRA_NN_HIT "):
                out["hits"][stems[int(head.split()[1])]] = names
            elif head.startswith("LRA_NN_SIG "):
                out["sigs"][head[len("LRA_NN_SIG "):].strip()] = rest.strip()
        except (IndexError, ValueError):
            continue
    if len(out["ns"]) != len(nss) or len(out["hits"]) != len(set(stems)):
        return None
    return out


def lake_runner(spec: EnvSpec, text: str, timeout: float) -> list[dict]:
    """One `lake env lean --json` run of `text` in the environment directory (as harness/leantools.lean_run), admitted by the memory gate;
    raises subprocess.TimeoutExpired on a timeout or a memgate give-up."""
    from scorer.compile import ELAN_BIN
    from scorer.memgate import run_lean
    scratch = spec.wd / "LRAScratch"; scratch.mkdir(exist_ok=True)
    f = scratch / f"nn_{uuid.uuid4().hex[:10]}.lean"; f.write_text(text)
    env = dict(os.environ, PATH=f"{ELAN_BIN}:{os.environ.get('PATH', '')}")
    try:
        pr = run_lean(["lake", "env", "lean", "--json", f"-M{os.environ.get('LRA_LEAN_MEMORY_MB', '16000')}", *spec.lean_args,
                       str(f.relative_to(spec.wd))], cwd=spec.wd, env=env, capture_output=True, text=True, timeout=timeout)
    finally:
        f.unlink(missing_ok=True)
    return parse_messages(pr.stdout)


# ---- cache ---------------------------------------------------------------------------------------------------------------------------
def _h(s: str) -> str:
    return hashlib.sha1(s.encode()).hexdigest()[:16]


def _write_json(p: Path, obj) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(f".{p.name}.{uuid.uuid4().hex[:8]}.tmp")
    tmp.write_text(json.dumps(obj, ensure_ascii=False))
    os.replace(tmp, p)


def _read_json(p: Path):
    try:
        return json.loads(p.read_text())
    except (OSError, ValueError):
        return None


class Cache:
    """<work root>/.name_neighbors/<environment key>/: ns-<hash>.json, stem-<hash>.json, sigs.json (merged under a lock)."""

    def __init__(self, work_root: Path, key: str):
        self.dir = Path(work_root) / CACHE_DIR / key

    def ns(self, ns: str) -> list[str] | None:
        d = _read_json(self.dir / f"ns-{_h(ns)}.json")
        return d["names"] if isinstance(d, dict) and d.get("ns") == ns else None

    def hits(self, stem: str) -> list[str] | None:
        d = _read_json(self.dir / f"stem-{_h(stem)}.json")
        return d["names"] if isinstance(d, dict) and d.get("stem") == stem else None

    def sigs(self) -> dict:
        d = _read_json(self.dir / "sigs.json")
        return d if isinstance(d, dict) else {}

    def put(self, res: dict, meta: dict | None = None) -> None:
        t = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        if meta and not (self.dir / "meta.json").exists():
            _write_json(self.dir / "meta.json", dict(meta, created=t))
        for ns, names in res.get("ns", {}).items():
            _write_json(self.dir / f"ns-{_h(ns)}.json", {"ns": ns, "names": names, "t": t})
        for stem, names in res.get("hits", {}).items():
            _write_json(self.dir / f"stem-{_h(stem)}.json", {"stem": stem, "names": names, "t": t})
        if res.get("sigs"):
            self.dir.mkdir(parents=True, exist_ok=True)
            with open(self.dir / ".lock", "a") as lk:
                fcntl.flock(lk, fcntl.LOCK_EX)
                cur = self.sigs(); cur.update(res["sigs"]); _write_json(self.dir / "sigs.json", cur)


# ---- the session ---------------------------------------------------------------------------------------------------------------------
class Session:
    """One per agent session: the query budget, the in-session failure memo and the per-row missing-names memory.
    lookup(errors) -> {unknown name: [one-line signatures]} (at most MAX_LINES lines in all; {} when nothing applies or anything fails)."""

    def __init__(self, work_root, row: dict | None = None, version: str | None = None, *, spec: EnvSpec | None = None,
                 ws_root=None, max_queries: int = MAX_QUERIES, timeout: float = QUERY_TIMEOUT, max_seconds: float = SESSION_SECONDS,
                 runner=None, log=None):
        self.work_root = Path(work_root); self.row = row; self.version = version; self._spec = spec
        self.ws_root = Path(ws_root) if ws_root else None
        self.max_queries, self.timeout, self.max_seconds = max_queries, timeout, max_seconds
        self.runner = runner or lake_runner; self.log = log or (lambda *_: None)
        self.failed: set = set()      # ("ns", ns) / ("stem", s) / ("sig", name) that failed in this session: never re-queried
        self.memo: dict = {}          # name -> (ranked names, confirmed missing): answered without Lean or ranking later in the session
        self._meta_first = False      # a module file whose query needed the meta import: later queries start with it
        self.stats = {"lookups": 0, "answered": 0, "lines": 0, "queries": 0, "seconds": 0.0, "query_failures": 0, "cache_answers": 0,
                      "skipped_budget": 0}
        self._spec_err = None
        self.note = NOTE

    def spec(self) -> EnvSpec | None:
        if self._spec is None and self._spec_err is None:
            try:
                self._spec = env_spec(self.row, self.version)
            except Exception as e:  # noqa: BLE001
                self._spec_err = f"{type(e).__name__}: {e}"
        return self._spec

    def key(self) -> str | None:
        s = self.spec()
        return s.key if s else None

    def budget_left(self) -> bool:
        return self.stats["queries"] < self.max_queries and self.stats["seconds"] < self.max_seconds

    def _run(self, spec: EnvSpec, nss: list[str], stems: list[str], sigs: list[str]) -> dict | None:
        """One query (a module file is retried once with the meta import, as scorer.compile does for arena_measure)."""
        for meta in ([True] if self._meta_first else [False, True] if spec.module else [False]):
            if not self.budget_left():
                self.stats["skipped_budget"] += 1
                return None
            text, first = query_text(spec, nss, stems, sigs, meta_import=meta)
            t0 = time.time(); self.stats["queries"] += 1
            try:
                msgs = self.runner(spec, text, min(self.timeout, max(1.0, self.max_seconds - self.stats["seconds"])))
            except (subprocess.TimeoutExpired, TimeoutError, OSError) as e:
                self.stats["seconds"] += time.time() - t0; self.stats["query_failures"] += 1
                self.log(f"name_neighbors: query failed ({type(e).__name__})")
                return None
            self.stats["seconds"] += time.time() - t0
            res = parse_query(msgs, first, nss, stems, sigs)
            if res is not None:
                self._meta_first = meta
                return res
            self.stats["query_failures"] += 1
        return None

    def lookup(self, errors) -> dict[str, list[str]]:
        try:
            out = self._lookup(errors)
        except Exception as e:  # noqa: BLE001  (a hint must never break a tool result)
            self.log(f"name_neighbors: {type(e).__name__}: {e}")
            return {}
        if out:
            self.stats["answered"] += 1; self.stats["lines"] += sum(len(v) for v in out.values())
        return out

    def text(self, errors) -> str:
        """The NAME NEIGHBORS block for a lean_run result ("" when nothing applies)."""
        return render(self.lookup(errors))

    @staticmethod
    def cap(nb: dict[str, list[str]]) -> dict[str, list[str]]:
        """A merged result (several variants of one batch) cut back to MAX_LINES lines."""
        return share_lines(nb, MAX_LINES)

    def _lookup(self, errors) -> dict[str, list[str]]:
        wanted = [n for n in unknown_names(errors) if not skip_name(n)][:MAX_NAMES]
        if not wanted:
            return {}
        spec = self.spec()
        if spec is None:
            return {}
        self.stats["lookups"] += 1
        cache = Cache(self.work_root, spec.key)
        plans = {n: plan(n, spec.context) for n in wanted if n not in self.memo}
        listings: dict[str, list[str]] = {}; hits: dict[str, list[str]] = {}
        need_ns, need_st = [], []
        for p in plans.values():
            for ns in p.namespaces:
                if ns in listings or ns in need_ns:
                    continue
                got = cache.ns(ns)
                if got is not None:
                    listings[ns] = got
                elif ("ns", ns) not in self.failed:
                    need_ns.append(ns)
            if p.stem not in hits and p.stem not in need_st:
                got = cache.hits(p.stem)
                if got is not None:
                    hits[p.stem] = got
                elif ("stem", p.stem) not in self.failed:
                    need_st.append(p.stem)
        if need_ns or need_st:
            res = self._run(spec, need_ns, need_st, [])
            if res is None:
                self.failed.update([("ns", x) for x in need_ns] + [("stem", x) for x in need_st])
            else:
                cache.put(res, {"wd": str(spec.wd), "toolchain": spec.toolchain, "lean_args": list(spec.lean_args)})
                listings.update(res["ns"]); hits.update(res["hits"])
        else:
            self.stats["cache_answers"] += 1
        for n, p in plans.items():
            if not any(ns in listings for ns in p.namespaces) and p.stem not in hits:
                continue   # nothing known about this name (its query failed)
            self.memo[n] = (rank(p, listings, hits.get(p.stem) or [], MAX_LINES), confirmed_missing(p, listings))
        chosen = share_lines({n: self.memo[n][0] for n in wanted if n in self.memo}, MAX_LINES)
        sigs = cache.sigs()
        need_sig = [c for v in chosen.values() for c in v if c not in sigs and ("sig", c) not in self.failed]
        if need_sig:
            res = self._run(spec, [], [], need_sig)
            if res is None:
                self.failed.update(("sig", c) for c in need_sig)
            else:
                cache.put(res); sigs.update(res["sigs"])
        out = {n: [self._line(c, sigs.get(c)) for c in v] for n, v in chosen.items()}
        if self.ws_root is not None:
            try:
                record_missing(self.ws_root, spec.key, {n: self.memo[n][0] for n in wanted if n in self.memo and self.memo[n][1]})
            except OSError:
                pass
        return out

    @staticmethod
    def _line(name: str, sig: str | None) -> str:
        """Lean's signature on one line, the universe parameters after the name dropped (`c.{u} (x : α) : P` -> `c (x : α) : P`)."""
        if not sig or sig.strip() == "?":
            return name
        s = one_line(sig)
        if s.startswith(name + ".{"):
            s = re.sub(r"^(\S+?)\.\{[^{}]*\}", r"\1", s, count=1)
        return s if s.startswith(name) else f"{name} : {s}"


# ---- missing names memory -------------------------------------------------------------------------------------------------------------
def record_missing(ws_root: Path, key: str, missing: dict[str, list[str]]) -> None:
    """Add confirmed-missing names (with their three nearest neighbours) to <workspace>/missing_names.json."""
    if not missing:
        return
    p = Path(ws_root) / MISSING_FILE; t = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    with open(Path(ws_root) / ".missing_names.lock", "a") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        cur = _read_json(p)
        cur = cur if isinstance(cur, dict) and isinstance(cur.get("names"), dict) else {"names": {}}
        for n, near in missing.items():
            e = cur["names"].get(n) or {"first": t, "count": 0}
            e.update({"env": key, "last": t, "count": int(e.get("count") or 0) + 1, "near": list(near)[:3] or e.get("near") or []})
            cur["names"][n] = e
        if len(cur["names"]) > 200:   # keep the most recent 200
            cur["names"] = dict(sorted(cur["names"].items(), key=lambda kv: kv[1].get("last", ""))[-200:])
        _write_json(p, cur)


def missing_block(ws_root, key: str | None = None, limit: int = MISSING_SHOW) -> str:
    """The opening-message block: names an earlier session wrote that Lean rejected and that are not constants of this environment
    (only records made in the same environment when `key` is given), most recent first, with the nearest real names."""
    d = _read_json(Path(ws_root) / MISSING_FILE) if ws_root else None
    if not isinstance(d, dict) or not isinstance(d.get("names"), dict):
        return ""
    ents = [(n, e) for n, e in d["names"].items() if isinstance(e, dict) and (key is None or e.get("env") == key)]
    if not ents:
        return ""
    ents.sort(key=lambda ne: (ne[1].get("last", ""), ne[1].get("count", 0)), reverse=True)
    parts = []
    for n, e in ents[:limit]:
        near = [x for x in e.get("near") or [] if isinstance(x, str)]
        parts.append(f"`{n}`" + (" (nearest real: " + ", ".join(f"`{x}`" for x in near) + ")" if near else ""))
    return ("NAMES KNOWN TO BE MISSING (an earlier session wrote them, Lean reported them unknown, and the environment's declaration list "
            "confirmed they do not exist as written; do not use them): " + "; ".join(parts))


