def main() -> int:
    ap = argparse.ArgumentParser(description="name neighbours of the unknown names in a Lean error text, from a row's environment")
    ap.add_argument("--problem", required=True)
    ap.add_argument("--errors", required=True, help="Lean error text (or @file)")
    ap.add_argument("--version", default=None, help="toolchain (default: the row's newest)")
    ap.add_argument("--work-root", default="harness/work_nn_cli", help="cache root (relative to the repository)")
    ap.add_argument("--rows", default="data/benchmark_warmup.jsonl")
    a = ap.parse_args()
    from probe.verify_candidates import newest_first
    rows = {json.loads(l)["name"]: json.loads(l) for l in (ROOT / a.rows).open() if l.strip()}
    row = rows[a.problem]; version = a.version or newest_first(row["version_info"])[0]
    errs = Path(a.errors[1:]).read_text() if a.errors.startswith("@") else a.errors
    s = Session(ROOT / a.work_root, row, version, log=lambda m: print(m, file=sys.stderr))
    t0 = time.time(); nb = s.lookup(errs)
    print(json.dumps({"name_neighbors": nb, "stats": s.stats, "seconds": round(time.time() - t0, 2), "key": s.key()}, ensure_ascii=False, indent=1))
    return 0


